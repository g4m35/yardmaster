// Bundles the CI guard GitHub Action into one dependency-free file: action/index.mjs (committed, because
// GitHub runs actions straight from the repository). `node scripts/build-action.mjs --check` fails if it's stale.
import { build } from 'esbuild';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const outfile = 'action/index.mjs';
const result = await build({
  entryPoints: ['src/ci/action-main.ts'],
  bundle: true,
  platform: 'node',
  target: 'node24',
  format: 'esm',
  write: false,
  legalComments: 'none',
  banner: { js: '// Generated by scripts/build-action.mjs from src/ci/. Do not edit by hand.' },
  logLevel: 'warning',
});
const code = result.outputFiles[0].text;
if (process.argv.includes('--check')) {
  if (!existsSync(outfile) || readFileSync(outfile, 'utf8') !== code) {
    console.error(`${outfile} is out of date. Run: node scripts/build-action.mjs`);
    process.exit(1);
  }
  console.log(`${outfile} is up to date`);
} else {
  writeFileSync(outfile, code);
  console.log(`built ${outfile} (${(code.length / 1024).toFixed(1)} KB)`);
}
